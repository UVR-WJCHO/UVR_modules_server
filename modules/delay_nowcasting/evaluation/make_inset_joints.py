#!/usr/bin/env python3
r"""make_inset_joints.py -- turn real 21-joint hand poses into the TikZ data file
used by the teaser figure's inset (research/paper/figures/inset_joints.tex).

The teaser inset must show REAL joints, not a hand-drawn glyph: the size of the
stale-pose error and the closeness of the forecast are quantitative claims.

Produce the input with
    modules/delay_nowcasting/evaluation/export_inset_pose.py
which picks the frame whose stale and forecast errors are both closest to the
split median, so the inset is representative rather than flattering.

Joint order: 0 wrist, 1-4 thumb, 5-8 index, 9-12 middle, 13-16 ring, 17-20 pinky.
3-D input is projected orthographically; image-space input has y down, so use
--flip-y.
"""
import argparse
import json
import os
import sys

import numpy as np

N_JOINTS = 21
TIP_MIDDLE = 12          # wrist -> middle-finger tip, the normalisation length


def load_poses(path):
    ext = os.path.splitext(path)[1].lower()
    if ext == ".npz":
        d = np.load(path)
        poses = {k: np.asarray(d[k], dtype=float) for k in ("gt", "stale", "pred")}
    elif ext == ".json":
        with open(path) as f:
            d = json.load(f)
        poses = {k: np.asarray(d[k], dtype=float) for k in ("gt", "stale", "pred")}
    else:
        raise SystemExit(f"unsupported input format: {ext}")
    for k, v in poses.items():
        if v.shape[0] != N_JOINTS:
            raise SystemExit(f"'{k}' has {v.shape[0]} joints, expected {N_JOINTS}")
    return poses


def normalise(poses, hand_cm, project, flip_y, zoom):
    """One similarity transform for all three poses, driven by the GT hand.

    The same transform is applied to every pose, so the relative offset between
    them -- which is what the inset is about -- is preserved exactly.
    """
    ax = {"xy": (0, 1), "xz": (0, 2), "zy": (2, 1)}[project]
    out = {k: np.array(v[:, ax] if v.shape[1] >= 3 else v[:, :2], dtype=float)
           for k, v in poses.items()}
    if flip_y:
        for k in out:
            out[k] = out[k] * np.array([1.0, -1.0])

    origin = out["gt"][0].copy()
    span = np.linalg.norm(out["gt"][TIP_MIDDLE] - out["gt"][0])
    if span <= 0:
        raise SystemExit("degenerate GT pose: wrist and middle tip coincide")
    scale = hand_cm / span * zoom
    return {k: (v - origin) * scale for k, v in out.items()}


def fmt(poses, source, real):
    lines = [
        "% inset_joints.tex -- joint coordinates (cm) for the teaser inset.",
        "% GENERATED by modules/delay_nowcasting/evaluation/make_inset_joints.py",
        "% Do not edit by hand; regenerate instead.",
        "%",
        "% Frame of reference: ground-truth wrist at (0,0), x right, y up,",
        "% a common similarity transform applied to all three poses.",
        "",
        r"\def\insetsource{%s}" % source,
        r"\insetreal%s" % ("true" if real else "false"),
        "",
    ]
    for key, macro in (("stale", r"\jointsstale"), ("gt", r"\jointsgt"),
                       ("pred", r"\jointspred")):
        items = ",".join("%d/%.4f/%.4f" % (i, x, y)
                         for i, (x, y) in enumerate(poses[key]))
        lines += [r"\def%s{%s}" % (macro, items), ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--input", required=True, help=".npz/.json with gt, stale, pred")
    ap.add_argument("--meta", help="export_inset_pose.py 가 쓴 .json (provenance 자동 기입)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--dataset", default="")
    ap.add_argument("--horizon", default="")
    ap.add_argument("--seq", default="")
    ap.add_argument("--hand-cm", type=float, default=0.82,
                    help="printed length of the GT wrist-to-middle-tip bone (cm)")
    ap.add_argument("--zoom", type=float, default=1.0)
    ap.add_argument("--project", default="xy", choices=["xy", "xz", "zy"])
    ap.add_argument("--flip-y", action="store_true",
                    help="input is in camera/image coordinates (y down)")
    args = ap.parse_args()

    dataset, horizon, seq = args.dataset, args.horizon, args.seq
    if args.meta:
        m = json.loads(open(args.meta).read())
        dataset = dataset or m.get("dataset", "")
        horizon = horizon or str(int(m.get("horizon_ms", 0)))
        seq = seq or f"{m.get('split','')} split"
    bits = [b for b in (dataset, f"{horizon}\\,ms horizon" if horizon else "", seq) if b]
    if not bits:
        print("warning: no provenance given; the caption will say so", file=sys.stderr)
    source = ", ".join(bits) if bits else "UNSPECIFIED SOURCE"
    real = bool(dataset and horizon)

    poses = normalise(load_poses(args.input), args.hand_cm, args.project,
                      args.flip_y, args.zoom)
    with open(args.out, "w") as f:
        f.write(fmt(poses, source, real))
    print("wrote %s  (%s)" % (args.out, source))
    hand = np.linalg.norm(poses["gt"][TIP_MIDDLE] - poses["gt"][0])
    for k in ("stale", "pred"):
        d = np.linalg.norm(poses["gt"] - poses[k], axis=1).mean()
        print("  %-6s mean joint offset: %.3f cm printed (%.0f%% of hand length)"
              % (k, d, d / hand * 100))


if __name__ == "__main__":
    main()
